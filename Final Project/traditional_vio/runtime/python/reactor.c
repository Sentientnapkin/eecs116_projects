// Reactor entry points of runtime.wasm: the EECS 116/216 solution ABI (docs/ABI.md) on top of the embedded CPython.
// The host calls frame_width() once (it starts Python and imports the solution), init() once with the config JSON,
// then step() per frame. The student's directory arrives as a zip that `viobench bundle` embeds into this module as a
// data segment; the bundler also patches the descriptor below with its address and length, so the module is
// self-contained and the host never handles the zip.
// Everything Python-specific lives in the frozen module viobench_guest (viobench/solution/runtime/python/guest/viobench_guest.py); this file only moves
// pointers across and reports exceptions on stderr.
#include <Python.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#include "../native/viobench_abi.h"  // the contract: export names, status codes, buffer layouts

#define ABI_VERSION VIOBENCH_ABI_VERSION
#define IMU_ROW_VALUES VIOBENCH_IMU_ROW_VALUES
#define STATE_VALUES VIOBENCH_STATE_VALUES
#define STATUS_OK VIOBENCH_STATUS_OK
#define STATUS_ERROR VIOBENCH_STATUS_ERROR

void wasm_python_register_modules(void);  // generated by viobench/solution/runtime/python/cpython/scripts/link.py: inittab + frozen table

static PyObject *shim = NULL;  // viobench_guest, imported by frame_width()
static PyObject *shim_step = NULL;
static Py_ssize_t frame_bytes = 0;

// Found by the bundler through its magic bytes (it must appear exactly once in the module's data segments) and
// patched in place: address and length of the embedded zip. volatile keeps the compiler from folding the zeros.
struct bundle_descriptor {
    char magic[16];
    uint32_t address;
    uint32_t length;
    uint32_t version;
    uint32_t reserved;
};
static volatile struct bundle_descriptor bundle = {"VIOBENCHBUNDLE1", 0, 0, 1, 0};

// PyErr_Print() would call exit() for SystemExit, which traps the instance; report it like any other exception.
static void report_exception(void) {
    if (PyErr_ExceptionMatches(PyExc_SystemExit)) {
        PyErr_Clear();
        fputs("solution raised SystemExit\n", stderr);
    } else {
        PyErr_Print();
    }
    fflush(NULL);
}

int32_t abi_version(void) {
    return ABI_VERSION;
}

// Host-side allocation in guest memory; blocks live as long as the instance (the host never frees them).
void *alloc(uint32_t size) {
    return malloc(size ? size : 1);
}

// The harness calls frame_width() first, init() only after it and step() only after a successful init(); none of them
// checks the order again. frame_width() starts Python, imports the solution and returns its Solution.frame_width.
int32_t frame_width(void) {
    wasm_python_register_modules();
    PyConfig py_config;
    PyConfig_InitIsolatedConfig(&py_config);
    py_config.site_import = 0;
    py_config.buffered_stdio = 0;  // stdout/stderr reach the host log files before a trap
    py_config.write_bytecode = 0;
    py_config.pathconfig_warnings = 0;
    py_config.install_signal_handlers = 0;
    py_config.parse_argv = 0;
    py_config.use_hash_seed = 1;  // deterministic str/bytes hashing
    py_config.hash_seed = 0;
    wchar_t *argv[] = {L"solution"};
    PyStatus status = PyConfig_SetArgv(&py_config, 1, argv);
    if (!PyStatus_Exception(status)) {
        status = PyConfig_SetString(&py_config, &py_config.program_name, L"solution");
    }
    if (!PyStatus_Exception(status)) {
        status = Py_InitializeFromConfig(&py_config);
    }
    PyConfig_Clear(&py_config);
    if (PyStatus_Exception(status)) {
        fprintf(stderr, "runtime: Python initialization failed: %s\n", status.err_msg ? status.err_msg : "unknown error");
        fflush(NULL);
        return STATUS_ERROR;
    }

    shim = PyImport_ImportModule("viobench_guest");
    if (shim == NULL) {
        report_exception();
        return STATUS_ERROR;
    }
    uint32_t bundle_address = bundle.address, bundle_length = bundle.length;  // the harness refuses a runtime without a bundle
    PyObject *bundle_view = PyMemoryView_FromMemory((char *)(uintptr_t)bundle_address, (Py_ssize_t)bundle_length, PyBUF_READ);
    PyObject *result = bundle_view != NULL ? PyObject_CallMethod(shim, "frame_width", "O", bundle_view) : NULL;
    Py_XDECREF(bundle_view);
    long width = result != NULL ? PyLong_AsLong(result) : -1;
    Py_XDECREF(result);
    if (width == -1 && PyErr_Occurred()) {
        report_exception();
        return STATUS_ERROR;
    }
    fflush(NULL);
    return (int32_t)width;  // STATUS_ERROR if the import failed (traceback on stderr); the harness accepts only 320 or 640
}

int32_t init(const char *config, uint32_t config_length) {
    PyObject *config_view = PyMemoryView_FromMemory((char *)config, (Py_ssize_t)config_length, PyBUF_READ);
    PyObject *result = config_view != NULL ? PyObject_CallMethod(shim, "init", "O", config_view) : NULL;
    Py_XDECREF(config_view);
    int32_t code = STATUS_ERROR;
    Py_ssize_t bytes = 0;
    if (result == NULL || !PyArg_ParseTuple(result, "in", &code, &bytes)) {
        report_exception();
        Py_XDECREF(result);
        return STATUS_ERROR;
    }
    Py_DECREF(result);
    if (code != STATUS_OK) {
        fflush(NULL);
        return code;
    }
    shim_step = PyObject_GetAttrString(shim, "step");
    if (shim_step == NULL) {
        report_exception();
        return STATUS_ERROR;
    }
    frame_bytes = bytes;
    fflush(NULL);
    return STATUS_OK;
}

// frame: height*width*3 uint8 RGB; imu: imu_count rows of [t, ax, ay, az, gx, gy, gz] float64 with
// t_prev < t <= t_frame; out: [x, y, z, qx, qy, qz, qw, vx, vy, vz, wx, wy, wz] float64 written on STATUS_OK.
int32_t step(double t, const uint8_t *frame, const double *imu, int32_t imu_count, double *out) {
    PyObject *frame_view = PyMemoryView_FromMemory((char *)frame, frame_bytes, PyBUF_READ);
    PyObject *imu_view = PyMemoryView_FromMemory((char *)imu, (Py_ssize_t)imu_count * IMU_ROW_VALUES * (Py_ssize_t)sizeof(double), PyBUF_READ);
    PyObject *out_view = PyMemoryView_FromMemory((char *)out, STATE_VALUES * (Py_ssize_t)sizeof(double), PyBUF_WRITE);
    int32_t code = STATUS_ERROR;
    if (frame_view != NULL && imu_view != NULL && out_view != NULL) {
        PyObject *result = PyObject_CallFunction(shim_step, "dOOO", t, frame_view, imu_view, out_view);
        if (result != NULL) {
            long value = PyLong_AsLong(result);
            if (value == -1 && PyErr_Occurred()) {
                report_exception();
            } else {
                code = (int32_t)value;
            }
            Py_DECREF(result);
        } else {
            report_exception();
        }
    } else {
        report_exception();
    }
    Py_XDECREF(frame_view);
    Py_XDECREF(imu_view);
    Py_XDECREF(out_view);
    fflush(NULL);
    return code;
}
