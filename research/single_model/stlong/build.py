"""Export lcJ weights and build GSLV with a default-off student switch."""
import argparse,json,sys,re
from pathlib import Path
H=Path(__file__).resolve().parent;SM=H.parent;ROOT=SM.parents[1]
sys.path[:0]=[str(ROOT),str(SM/'learned_c'),str(SM/'learned')]
from research.single_model import run_variant as RV
import export_net
RV.OUT=H/'builds'
p=argparse.ArgumentParser();p.add_argument('--run');p.add_argument('--name',required=True);p.add_argument('--rep',type=int,default=0);p.add_argument('--off',action='store_true');p.add_argument('--sigscale',type=float,default=1.0);p.add_argument('--vscale',type=float,default=1.0);p.add_argument('--speedk',type=float,default=0.0);a=p.parse_args()
s=(SM/'learnvel/final/gslm_lvnet.c').read_text()
if a.run:
    run=Path(a.run);cfg=json.load(open(run/'result.json'))['args'];width=cfg.get('width',1.0);assert width in (1.0,1.5)
    header=H/'runs'/f'{a.name}_w.h';export_net.export(str(run),str(header),1.0,64,width)
    if a.vscale!=1 or a.sigscale!=1:
        # Constant speed calibration folded into the velocity outputs, no C runtime cost.
        import numpy as np
        arr=np.load(header.with_suffix('.npz')); arrays={k:arr[k].copy() for k in arr.files}
        cols=[0,1,2,6,7,8];arrays['LC_H2W'][:,cols]*=a.vscale;arrays['LC_H2B'][cols]*=a.vscale
        arrays['LC_H2B'][[3,4,5,9,10,11]]+=2*np.log(a.sigscale)
        text=header.read_text()
        for k in ['LC_H2W','LC_H2B']:
            x=arrays[k].ravel();block=f'static const float {k}[{len(x)}] = {{\n'+',\n'.join(','.join(f'{v:.9g}' for v in x[i:i+8]) for i in range(0,len(x),8))+',\n};'
            text=re.sub(r'static const float '+k+r'\[\d+\] = \{.*?\};',lambda _:block,text,flags=re.S)
        header.write_text(text);np.savez(header.with_suffix('.npz'),**arrays)
    i=s.index('#if LV_NET\n/* generated by export_net.py');j=s.index('#else',i)
    # Nest only the v700b weight block, preserving original fallback paths exactly.
    s=s[:i]+s[i:j].replace('#if LV_NET\n','#if LV_NET\n#if LV_STLONG\n'+header.read_text()+'\n#else\n',1)+'#endif\n'+s[j:]
    if width > 1:
        # CO<=72 and CI<=48: 9*48*2047^2 = 1,810,170,288 < INT32_MAX.
        old='static int16_t nsq_w[4][9 * 32 * 48 + 64];'
        assert s.count(old)==1
        s=s.replace(old,'#if LV_STLONG\nstatic int16_t nsq_w[4][9 * 48 * 72 + 64];\n#else\n'+old+'\n#endif')
        old='v128_t acc[12]; for (int q = 0; q < CO / 4; q++)'
        assert s.count(old)==1
        s=s.replace(old,'\n#if LV_STLONG\n        v128_t acc[18];\n#else\n        v128_t acc[12];\n#endif\n        for (int q = 0; q < CO / 4; q++)')
        old='units = 0; while (units < GOV_UMAX && GOV_B - gov_used > GC_UNIT) { units++; gov_used += GC_UNIT; }'
        assert s.count(old)==1
        new='units = 0; while (units < GOV_UMAX) { int k = ns_pos + units; double cost = GC_UNIT; if (k >= 62 && k < 74) cost *= 1.5; else if (k >= 74 && k < 95) cost *= 2.25; else if (k >= 95 && k < 97) cost *= 1.5; if (GOV_B - gov_used <= cost) break; units++; gov_used += cost; }'
        s=s.replace(old,'\n#if LV_STLONG\n        '+new+'\n#else\n        '+old+'\n#endif')
else: assert a.off
if a.speedk:
    marker='sd[i] = s < fl ? fl : s; mu[i] = lc_out[6 + i];'
    assert s.count(marker)==1
    s=s.replace(marker,marker+'\n#if LV_STLONG\n        mu[i] *= 1.0 + '+str(a.speedk)+' * (spd > 0.5 ? spd - 0.5 : 0.0);\n#endif')
src=H/'runs'/f'{a.name}.c';src.write_text('#ifndef LV_STLONG\n#define LV_STLONG 0\n#endif\n'+s)
defs='' if a.off else 'LV_STLONG=1'
if a.rep==1:defs+=' PIXEL_STD=1.515 DETECT_MIN_SCORE=1010.0'
if a.rep==2:defs+=' PIXEL_STD=1.485 DETECT_MIN_SCORE=990.0'
name=a.name+('' if not a.rep else f'_r{a.rep}')
wasm=RV.build(src,SM/'learnvel/CMakeLists.txt',defs,name)
import hashlib
sha=hashlib.sha256(wasm.read_bytes()).hexdigest();print(str(wasm),sha)
if a.off: assert sha=='5e4d2a0d40333b3f5152d60de84a688abc5d0eec8c1c73fa402dc9907839d196'
