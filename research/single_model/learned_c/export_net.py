"""Export a trained learned/train.py Net (nf=2, res=64, width 1) to a C header with BatchNorm folded, float32.
  python -B export_net.py <run dir containing best.pt> <out.h> [--sigscale s]
Layouts (all row-major, chosen so the inner C loop runs over output channels):
  LC_W{i}[ky][kx][ci][co], LC_B{i}[co]; LC_FW0[in][32], LC_FB0; LC_H1W[608][128] (rows 0..575 = CNN flatten in H,W,C order, 576..607 = IMU embedding), LC_H1B; LC_H2W[128][12], LC_H2B."""
import sys, json
from pathlib import Path
import numpy as np, torch
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'learned'))
import train as T

def export(run, outh, sigscale=1.0, res=64, width=1.0):
    net = T.Net(res, width, 2, 19); net.load_state_dict(torch.load(Path(run) / 'best.pt', map_location='cpu')); net.eval()
    arrs = {}; mods = list(net.cnn)
    li = 0; chs = []
    for i in range(0, len(mods), 3):
        conv, bn = mods[i], mods[i + 1]
        s = bn.weight / torch.sqrt(bn.running_var + bn.eps)
        w = conv.weight * s[:, None, None, None]; b = bn.bias - bn.running_mean * s
        arrs[f'LC_W{li}'] = w.permute(2, 3, 1, 0).detach().numpy().astype(np.float32)  # co,ci,ky,kx -> ky,kx,ci,co
        arrs[f'LC_B{li}'] = b.detach().numpy().astype(np.float32); chs.append(conv.out_channels); li += 1
    arrs['LC_FW0'] = net.fv[0].weight.detach().t().numpy().astype(np.float32); arrs['LC_FB0'] = net.fv[0].bias.detach().numpy()
    C = chs[-1]; W1 = net.head[0].weight.detach()  # (128, C*12+32), flatten order c*12 + h*4 + w
    cnn = W1[:, :C * 12].reshape(128, C, 3, 4).permute(0, 2, 3, 1).reshape(128, 12 * C)  # -> h,w,c
    arrs['LC_H1W'] = torch.cat([cnn, W1[:, C * 12:]], 1).t().numpy().astype(np.float32); arrs['LC_H1B'] = net.head[0].bias.detach().numpy()
    arrs['LC_H2W'] = net.head[2].weight.detach().t().numpy().astype(np.float32); arrs['LC_H2B'] = net.head[2].bias.detach().numpy()
    lines = [f'/* generated by export_net.py from {run}: BN folded, float32 */', f'#define LC_SIGSCALE {sigscale}f', '#define LC_C0 %d\n#define LC_C1 %d\n#define LC_C2 %d\n#define LC_C3 %d' % tuple(chs)]
    tot = 0
    for k, a in arrs.items():
        a = np.ascontiguousarray(a, dtype=np.float32).ravel(); tot += a.size
        lines.append(f'static const float {k}[{a.size}] = {{')
        for i in range(0, a.size, 8): lines.append(','.join(f'{x:.9g}' for x in a[i:i + 8]) + ',')
        lines.append('};')
    Path(outh).write_text('\n'.join(lines) + '\n'); print('floats', tot, 'bytes', tot * 4)
    np.savez(Path(outh).with_suffix('.npz'), **{k: v for k, v in arrs.items()})

if __name__ == '__main__':
    ss = float(sys.argv[sys.argv.index('--sigscale') + 1]) if '--sigscale' in sys.argv else 1.0
    export(sys.argv[1], sys.argv[2], ss)
