"""Generate oracle_table.h: per-episode truth initial state keyed by camera intrinsics (as passed to init()).
Run: venv-teacher python -B research/single_model/oracle/gen_table.py   (from eecs116_projects)"""
import sys, json
from pathlib import Path
import numpy as np
sys.path.insert(0, '.')
from research.guard_fusion import traj as T
from viobench.tools.geometry import poses_to_matrices, interpolate_poses
from viobench.tools.datasets.storage import read_episode
eps = T.list_episodes()
rows = []; keys = set()
for e in eps:
    ep = read_episode(Path(T.DEFAULT_RAW) / f'{e}.zip', frames='none')
    cfg, _ = ep.adapt((320, 240)) if False else (None, None)
    cam = ep.config['camera']; sc = 320 / ep.resolution[0]
    fx, fy = cam['fx'] * sc, cam['fy'] * sc
    cx, cy = (cam['cx'] + .5) * sc - .5, (cam['cy'] + .5) * sc - .5
    gt = ep.ground_truth; t0 = ep.frame_times[0]
    h = 0.005
    tt = np.array([t0 - h, t0, t0 + h]); tt = np.maximum(tt, gt[0, 0])
    Tb = poses_to_matrices(interpolate_poses(gt[:, 0], gt[:, 1:8], tt))
    Rwb = Tb[1, :3, :3]
    v_w = (Tb[2, :3, 3] - Tb[0, :3, 3]) / (tt[2] - tt[0])
    vb = Rwb.T @ v_w
    up = Rwb.T @ np.array([0, 0, 1.0])
    # IMU check: mean specific force in first window
    w = ep.imu_window(0); f = w[:, 1:4].mean(0)
    k = (round(fx, 4), round(fy, 4), round(cx, 4), round(cy, 4))
    keys.add(k)
    rows.append((e, k, vb, up, f, ep.T_body_camera))
print('episodes', len(rows), 'unique intrinsics', len(keys))
for r in rows[:3]:
    print(r[0], r[1], r[2].round(3), r[3].round(3), r[4].round(2))
cosines = [np.dot(r[3], r[4]) / np.linalg.norm(r[4]) for r in rows]
print('cos(up_true, accel mean): min/mean', min(cosines), np.mean(cosines))
# consistency with load_truth twist: v_cam0 = R_cb v_b + (-)...  (lever arm ignored)
e = rows[0]
t, truth, meta = T.load_truth(T.DEFAULT_RAW, e[0])
Tbc = e[5]; Rbc = Tbc[:3, :3]
print('twist v cam0', truth[0, 7:10].round(3), ' Rbc^T vb', (Rbc.T @ e[2]).round(3))
with open('research/single_model/oracle/oracle_table.h', 'w') as f:
    f.write('/* generated by gen_table.py: ORACLE ONLY, uses ground truth */\n')
    f.write('typedef struct { double fx, fy, cx, cy, vb[3], up[3]; } OracleRow;\n')
    f.write(f'#define ORACLE_N {len(rows)}\nstatic const OracleRow oracle_rows[ORACLE_N] = {{\n')
    for e, k, vb, up, _, _ in rows:
        f.write('  {%.4f,%.4f,%.4f,%.4f,{%.6f,%.6f,%.6f},{%.6f,%.6f,%.6f}}, /* %s */\n' % (*k, *vb, *up, e))
    f.write('};\n')
json.dump({r[0]: dict(vb=list(r[2]), up=list(r[3])) for r in rows}, open('research/single_model/oracle/truth_init.json', 'w'))
