"""Build learned_table_<tag>.h: PREDICTED start velocity (body frame) + sigma for each selected flight of folds 0-3 (fold 4 absent -> MISS).
  python -B tabgen.py <tag> <model name> [<model name> ...]    (models are ensembled; they must share nf/gap)
Predictions use only frames 0..K and the IMU up to frame K of each episode (K = gap*(nf-1)*5 frames), never truth."""
import json, sys
from pathlib import Path
import numpy as np, torch
sys.path.insert(0, str(Path(__file__).parent))
import train as T, evalnets as E, split

tag, names = sys.argv[1], sys.argv[2:]
a0 = json.load(open(T.OUT / names[0] / 'result.json'))['args']
K = a0['gap'] * (a0['nf'] - 1) * 5
rows = {r['name']: r for r in split.load_rows()}
ps = []
for n in names:
    q = []
    for role in ('val', 'search_sel'):
        p = E.run(n, role)
        q.append(p)
    ps.append(q)
entries = []
for ri, role in enumerate(('val', 'search_sel')):
    p = E.ensemble([q[ri] for q in ps])
    for fi, nm in enumerate(p['names']):
        if not p['selected'][fi]:
            continue
        i = int(np.nonzero((p['flight'] == fi) & (p['pos'] == 0))[0][0])
        entries.append((nm, p['mu'][i], np.exp(0.5 * p['lv'][i]), p['y'][i]))
cache = Path('/data/backups/rganapa/Sebastian/tmp/learned_cache')
hdr = ['/* generated by tabgen.py: PREDICTED velocity from the net (no truth). fold-4 flights are absent (MISS = baseline behaviour) */',
       'typedef struct { double fx, fy, cx, cy, mu0[3], sd0[3], muK[3], sdK[3]; } LearnRow;']
body = []
errs = []
for nm, mu, sd, y in entries:
    d = np.load(cache / f'{nm}.npz'); k = d['K'] * 5.0  # 128 -> 640 px, then 320 wide
    # filter intrinsics at 320x240: fx320 = fx640/2, cx = (cx640+.5)/2-.5
    import importlib
    fx = float(d['fx320']); fy = fx; cx = 159.5; cy = 119.5
    body.append('  {%.4f,%.4f,%.4f,%.4f,{%.5f,%.5f,%.5f},{%.5f,%.5f,%.5f},{%.5f,%.5f,%.5f},{%.5f,%.5f,%.5f}}, /* %s */' % (
        fx, fy, cx, cy, *mu[0], *sd[0], *mu[1], *sd[1], nm))
    errs.append(np.linalg.norm(mu[0] - y[0]))
hdr += [f'#define LEARN_N {len(body)}', '#define LEARN_K %d' % K, 'static const LearnRow learn_rows[LEARN_N] = {'] + body + ['};']
Path(__file__).parent.joinpath(f'learned_table_{tag}.h').write_text('\n'.join(hdr) + '\n')
print(tag, 'rows', len(body), 'K', K, 'mean head0 error vs truth (diagnostic only) %.3f' % np.mean(errs))
