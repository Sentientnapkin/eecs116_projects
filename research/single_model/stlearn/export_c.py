"""Fold BatchNorm and write the teacher weights as C arrays (dt_weights.h) for dt_core.h.

  vio_env/Scripts/python export_c.py --ckpt runs/t1/best.pt --out out/dt_weights.h
"""
import argparse
from pathlib import Path
import numpy as np
import torch

from models import load


def fold(seq):
    conv, bn = seq[0], seq[1]
    s = (bn.weight / torch.sqrt(bn.running_var + bn.eps)).detach()
    w = (conv.weight.detach() * s[:, None, None, None]).float().numpy()
    b = (bn.bias.detach() - bn.running_mean * s).float().numpy()
    return w, b, conv.out_channels, conv.stride[0]


def arr(name, a):
    a = np.asarray(a, np.float32).ravel()
    body = ",".join(f"{x:.9g}" for x in a)
    return f"static const float {name}[{a.size}] = {{{body}}};\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    m, ck = load(a.ckpt); assert m.cfg["aux"] == 10; m.eval()
    out = []
    enc = [fold(l) for l in m.enc]
    out.append(f"#define DT_ENC_N {len(enc)}\n#define DT_ENC_C {enc[-1][2]}\n#define DT_FC {m.fc1.out_features}\n#define DT_H2C {m.head[-1][0].out_channels}\n")
    for i, (w, b, co, s) in enumerate(enc):
        out += [arr(f"dt_enc_w{i}", w), arr(f"dt_enc_b{i}", b)]
    out.append("static const float *dt_enc_w[] = {" + ",".join(f"dt_enc_w{i}" for i in range(len(enc))) + "};\n")
    out.append("static const float *dt_enc_b[] = {" + ",".join(f"dt_enc_b{i}" for i in range(len(enc))) + "};\n")
    out.append("static const int dt_enc_co[] = {" + ",".join(str(e[2]) for e in enc) + "};\n")
    out.append("static const int dt_enc_s[] = {" + ",".join(str(e[3]) for e in enc) + "};\n")
    hd = [fold(l) for l in m.head]
    v3 = getattr(m, "v3", False)
    assert [h[3] for h in hd] == ([2, 1, 2, 1] if v3 else [1, 2, 1])
    if v3:
        out.append("#define DT_V3 1\n")
    for i, (w, b, co, s) in enumerate(hd):
        out += [arr(f"dt_h_w{i}", w), arr(f"dt_h_b{i}", b)]
    out.append("static const float *dt_h_w[] = {" + ",".join(f"dt_h_w{i}" for i in range(len(hd))) + "};\n")
    out.append("static const float *dt_h_b[] = {" + ",".join(f"dt_h_b{i}" for i in range(len(hd))) + "};\n")
    out.append("static const int dt_h_co[] = {" + ",".join(str(h[2]) for h in hd) + "};\n")
    for n, l in (("fc1", m.fc1), ("fc2", m.fc2), ("out", m.out)):
        out += [arr(f"dt_{n}_w", l.weight.detach().numpy()), arr(f"dt_{n}_b", l.bias.detach().numpy())]
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("/* generated by export_c.py from %s */\n" % Path(a.ckpt).name + "".join(out))
    print("wrote", a.out, Path(a.out).stat().st_size // 1024, "KB")


if __name__ == "__main__":
    main()
