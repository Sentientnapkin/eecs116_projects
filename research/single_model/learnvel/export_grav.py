"""export_grav.py RUN OUT.h : gravity net (nf=1, res 64, width 1, nvec 7) -> C arrays GR_* (BN folded, float32); same layouts as learned_c/export_net.py"""
import sys, json
from pathlib import Path
import numpy as np, torch
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'learned'))
import train as T
run, outh = Path(sys.argv[1]), sys.argv[2]
a = json.load(open(run / 'result.json'))['args']; assert a['res'] == 64
net = T.Net(64, a['width'], 1, 7); net.load_state_dict(torch.load(run / 'best.pt', map_location='cpu')); net.eval()
arrs = {}; mods = list(net.cnn); chs = []
for li, i in enumerate(range(0, len(mods), 3)):
    conv, bn = mods[i], mods[i + 1]; s = bn.weight / torch.sqrt(bn.running_var + bn.eps)
    arrs[f'GR_W{li}'] = (conv.weight * s[:, None, None, None]).permute(2, 3, 1, 0).detach().numpy(); arrs[f'GR_B{li}'] = (bn.bias - bn.running_mean * s).detach().numpy(); chs.append(conv.out_channels)
arrs['GR_FW0'] = net.fv[0].weight.detach().t().numpy(); arrs['GR_FB0'] = net.fv[0].bias.detach().numpy()
C = chs[-1]; W1 = net.head[0].weight.detach(); cnn = W1[:, :C * 12].reshape(128, C, 3, 4).permute(0, 2, 3, 1).reshape(128, 12 * C)
arrs['GR_H1W'] = torch.cat([cnn, W1[:, C * 12:]], 1).t().numpy(); arrs['GR_H1B'] = net.head[0].bias.detach().numpy()
arrs['GR_H2W'] = net.head[2].weight.detach().t().numpy(); arrs['GR_H2B'] = net.head[2].bias.detach().numpy()
L = [f'/* gravity net generated by learnvel/export_grav.py from {run.name}: BN folded, float32 */', '#define GR_C0 %d\n#define GR_C1 %d\n#define GR_C2 %d\n#define GR_C3 %d' % tuple(chs)]
for k, v in arrs.items():
    v = np.ascontiguousarray(v, dtype=np.float32).ravel(); L.append(f'static const float {k}[{v.size}] = {{')
    for i in range(0, v.size, 8): L.append(','.join(f'{x:.9g}' for x in v[i:i + 8]) + ',')
    L.append('};')
Path(outh).write_text('\n'.join(L) + '\n'); np.savez(Path(outh).with_suffix('.npz'), **arrs); print('ok', chs)
