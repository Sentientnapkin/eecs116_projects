"""mknet.py RUN OUT.c [--sigscale s] : lv.c with the lcJ weight block replaced by the weights of RUN (nf=2, res 64, width from result.json).
Off-switch: the default lv.c (lcJ) is the HM40 build; this writes a separate source."""
import sys, json, re
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'learned_c'))
import export_net
run, out = Path(sys.argv[1]), Path(sys.argv[2]); ss = float(sys.argv[sys.argv.index('--sigscale') + 1]) if '--sigscale' in sys.argv else 1.0
a = json.load(open(run / 'result.json'))['args']; assert a.get('nf', 2) == 2 and a['res'] == 64 and a.get('gap', 1) == 1
tmp = HERE / 'runs' / (run.name + '_w.h'); export_net.export(str(run), str(tmp), ss, 64, a['width'])
s = (HERE / 'lv.c').read_text(); i = s.index('/* generated by export_net.py from research/single_model/learned_c/runs/lcJ')
j = s.index('static const float LC_H2B[12] = {', i); j = s.index('};', j) + 3
s = s[:i] + tmp.read_text() + s[j:]
out.write_text(s); print('wrote', out)
