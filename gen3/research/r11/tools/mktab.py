"""mktab.py LIST OUT_PREFIX: oracle tables (OFFLINE / TEST builds only, never a submission) for every flight in LIST (zip paths).
Writes OUT_PREFIX.h (C table: key = first IMU row of frame 0, per-frame GT body(IMU-axes) velocity, frame-0 body 'up' (specific force
direction at rest), initial gyro/accel bias LS estimates over the first 2 s) and OUT_PREFIX.npz (same + per-frame body gravity, omega).
Run: PYTHONPATH=/dev/shm/sebastian-vio/viobench venv-viobench-9b1b079/bin/python mktab.py LIST OUT"""
import sys, numpy as np
from pathlib import Path
from viobench.tools.datasets.storage import read_episode
from viobench.tools.geometry import interpolate_poses

def q2R(q):  # x y z w
    x, y, z, w = q.T
    return np.stack([1-2*(y*y+z*z), 2*(x*y-z*w), 2*(x*z+y*w), 2*(x*y+z*w), 1-2*(x*x+z*z), 2*(y*z-x*w),
                     2*(x*z-y*w), 2*(y*z+x*w), 1-2*(x*x+y*y)], -1).reshape(-1, 3, 3)

def logR(R):
    c = np.clip((np.trace(R, axis1=1, axis2=2) - 1) / 2, -1, 1); a = np.arccos(c)
    v = np.stack([R[:, 2, 1]-R[:, 1, 2], R[:, 0, 2]-R[:, 2, 0], R[:, 1, 0]-R[:, 0, 1]], -1)
    s = np.where(a < 1e-9, 0.5, a / (2*np.sin(np.maximum(a, 1e-12))))
    return v * s[:, None]

files = [l.strip() for l in open(sys.argv[1]) if l.strip()]
out = sys.argv[2]
keys, vb, up0, bgs, bas, names, nfr, gbs, diag = [], [], [], [], [], [], [], [], []
for f in files:
    ep = read_episode(Path(f), frames='none')
    gt = ep.ground_truth  # t, p(3), q(xyzw) of the BODY (imu) frame
    assert np.allclose(ep.T_body_camera[:3, 3], 0), 'lever arm'
    ft = ep.frame_times; h = 0.005
    P = lambda t: interpolate_poses(gt[:, 0], gt[:, 1:8], t)
    pb, pn, pa = P(np.maximum(ft-h, gt[0, 0])), P(ft), P(np.minimum(ft+h, gt[-1, 0]))
    Rn = q2R(pn[:, 3:7])
    vw = (pa[:, :3]-pb[:, :3]) / (2*h)
    v_b = np.einsum('nji,nj->ni', Rn, vw)            # R^T v
    g_b = np.einsum('nji,j->ni', Rn, np.array([0, 0, 1.0]))  # body 'up' (specific force direction at rest)
    # bias LS over the first 2 s: GT samples are on the IMU grid
    imu = ep.imu  # t, a(3), g(3)  (ABI order)
    t0 = ft[0]; m = (imu[:, 0] >= t0) & (imu[:, 0] <= t0 + 2.0)
    ti = imu[m, 0]
    Pi = P(ti); Pm_ = P(ti-h); Pp = P(ti+h)
    Ri, Rm, Rp = q2R(Pi[:, 3:7]), q2R(Pm_[:, 3:7]), q2R(Pp[:, 3:7])
    w_true = logR(np.einsum('nji,njk->nik', Rm, Rp)) / (2*h)
    a_w = (Pp[:, :3] - 2*Pi[:, :3] + Pm_[:, :3]) / h**2
    f_true = np.einsum('nji,nj->ni', Ri, a_w - np.array([0, 0, -9.81]))
    eg = imu[m, 4:7] - w_true; ea = imu[m, 1:4] - f_true
    bg, ba = eg.mean(0), ea.mean(0)
    diag.append((eg.std(0).mean(), ea.std(0).mean()))
    k = ep.imu_window(0)[0]
    keys.append(k[1:7]); vb.append(v_b.astype(np.float32)); up0.append(g_b[0]); bgs.append(bg); bas.append(ba)
    names.append(Path(f).stem); nfr.append(len(ft)); gbs.append(g_b.astype(np.float32))
    print(names[-1], len(ft), 'v0 %.2f' % np.linalg.norm(v_b[0]), 'bg', np.round(bg, 4), 'ba', np.round(ba, 3), 'res sd g %.3f a %.3f' % diag[-1], flush=True)
N = max(nfr); F = len(files)
V = np.zeros((F, N, 3), np.float32)
for i, v in enumerate(vb): V[i, :len(v)] = v
np.savez_compressed(out + '.npz', names=np.array(names), keys=np.array(keys), vb=V, up0=np.array(up0), bg=np.array(bgs), ba=np.array(bas),
                    gb=np.stack([np.pad(g, ((0, N-len(g)), (0, 0))) for g in gbs]), nfr=np.array(nfr), diag=np.array(diag))
L = [f'/* generated by r11/tools/mktab.py: ORACLE TABLE, test builds only */', f'#define OR_F {F}', f'#define OR_NF {N}',
     'static const double OR_KEY[OR_F][6] = {' + ','.join('{' + ','.join('%.17g' % x for x in k) + '}' for k in keys) + '};',
     'static const double OR_UP0[OR_F][3] = {' + ','.join('{%.9g,%.9g,%.9g}' % tuple(u) for u in up0) + '};',
     'static const double OR_BG[OR_F][3] = {' + ','.join('{%.6g,%.6g,%.6g}' % tuple(u) for u in bgs) + '};',
     'static const double OR_BA[OR_F][3] = {' + ','.join('{%.6g,%.6g,%.6g}' % tuple(u) for u in bas) + '};',
     'static const float OR_VT[OR_F][OR_NF][3] = {']
for i in range(F):
    L.append('{' + ','.join('{%.4f,%.4f,%.4f}' % tuple(v) for v in V[i]) + '},')
L.append('};')
open(out + '.h', 'w').write('\n'.join(L) + '\n')
print('wrote', out, F, 'flights')
