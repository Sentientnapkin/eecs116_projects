"""gen_oracle.py OUT.h POOL... : per-flight privileged init table for oracle-ceiling builds (OFFLINE ONLY, never shipped).
key = sum|first IMU row of frame-0 window (6 values)|; ub = true up (+z world) in IMU body axes at frame 0;
vb = true IMU velocity in body axes at frame 0 (camera-centre velocity rotated, lever arm included)."""
import sys, glob, numpy as np
from multiprocessing import Pool
from viobench.tools.datasets.storage import read_episode
from viobench.tools.geometry import quaternion_to_matrix
def one(z):
    ep = read_episode(z, frames='none')
    w = ep.imu_window(0); key = float(np.sum(np.abs(w[0, 1:7])))
    Tci = np.array(ep.config['imu']['T_cam_imu']).reshape(4, 4); Rcb = Tci[:3, :3]
    Tic = np.linalg.inv(Tci); Rbc, pbc = Tic[:3, :3], Tic[:3, 3]
    pw = ep.camera_poses_world()[0]; Rwc = quaternion_to_matrix(pw[3:7]); Rwb = Rwc @ Rcb
    ub = Rwb.T @ np.array([0, 0, 1.0])
    tw = ep.ground_truth_twist()[0]; vc, wc = tw[:3], tw[3:]
    wb = Rbc @ wc; vb = Rbc @ vc - np.cross(wb, pbc)
    return z.split('/')[-1][:-4], key, ub, vb
if __name__ == '__main__':
    zs = sorted(sum((glob.glob(p + '/*.zip') for p in sys.argv[2:]), []))
    with Pool(8) as p: rows = p.map(one, zs)
    keys = np.array([r[1] for r in rows]); ks = np.sort(keys); print('n', len(rows), 'min key gap', np.min(np.diff(ks)))
    with open(sys.argv[1], 'w') as f:
        f.write('/* generated by tools/gen_oracle.py: OFFLINE ORACLE ONLY */\nstatic const double r3_otab[][7] = {\n')
        for n, k, u, v in rows: f.write('{%.12g,%.9f,%.9f,%.9f,%.6f,%.6f,%.6f}, /* %s */\n' % (k, *u, *v, n))
        f.write('};\n#define R3_ON %d\n' % len(rows))
