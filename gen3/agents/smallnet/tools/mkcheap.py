"""mkcheap.py RUN OUT_net.c [--q16 1] [--stepf F]: standalone net.c for agents/cheap's net.h API (net_cam, net_begin, net_feed, net_nsteps,
net_cost, net_total, net_pos, net_done, net_tick, net_out) built from a smallnet lv5 run (pre=lo). Same IMU features as the cheap template
(lc_exp / lc_rows copied verbatim from agents/cheap/tools/net_tmpl_body.c at generation time). Differences vs the cheap template:
 - the low-res gray of frame s / frame s+K is computed INSIDE net_begin / net_feed (no 230 KB RGB stash; costs ~SN gray fuel there);
 - micro-steps (prep, norm, convs, head) = SN_STEPS; net_cost(k) = measured-style estimate per step (snbench numbers at generation).
Do not edit agents/cheap files; copy the output there yourself (their tools/mknet.py regenerates src/net.c otherwise)."""
import sys, argparse, re
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent)); import mksn
ap = argparse.ArgumentParser(); ap.add_argument('run'); ap.add_argument('out'); ap.add_argument('--q16', type=int, default=1); ap.add_argument('--stepf', type=float, default=120e3)
ap.add_argument('--costs', default='', help='comma list of measured fuel per step (snbench); default: generator estimate')
a = ap.parse_args()
blk, info = mksn.gen(a.run, a.stepf, q16=a.q16)
body = Path('/data/backups/rganapa/Sebastian/gen3/agents/cheap/tools/net_tmpl_body.c').read_text().split('\n')
i = next(k for k, l in enumerate(body) if l.startswith('static void lc_exp('))
j = next(k for k, l in enumerate(body) if l.startswith('static void lc_rows(')); j = next(k for k in range(j, len(body)) if body[k] == '}')
imu = body[i:j + 1]
costs = [float(x) for x in a.costs.split(',')] if a.costs else [120e3] * info['steps']
assert len(costs) == info['steps'], (len(costs), info['steps'])
o = [f'/* GENERATED by agents/smallnet/tools/mkcheap.py from {a.run} (q16={a.q16}) -- smallnet learned velocity net, net.h API */',
     '#include <stdint.h>', '#include <string.h>', '#include <math.h>', '#include <wasm_simd128.h>', '#include "net.h"',
     'static double fx, cx, cy, R_bc[9];',
     'static void m3mul(const double *a, const double *b, double *c) { for (int i = 0; i < 3; i++) for (int j = 0; j < 3; j++) c[3 * i + j] = a[3 * i] * b[j] + a[3 * i + 1] * b[3 + j] + a[3 * i + 2] * b[6 + j]; }',
     'static void m3tmul(const double *a, const double *b, double *c) { for (int i = 0; i < 3; i++) for (int j = 0; j < 3; j++) c[3 * i + j] = a[i] * b[j] + a[3 + i] * b[3 + j] + a[6 + i] * b[6 + j]; }',
     'static double lc_Rc[9], lc_Vi[3], lc_Rs[9], lc_Vs[3], lc_R5[9], lc_V5[3], lc_fm[2][3], lc_gm[2][3], lc_tprev;',
     'static int lc_have_row, ns_have5, nt_frame, nt_pos;']
o += imu + [blk]
o += [f'static const double sn_cost[{len(costs)}] = {{' + ', '.join(f'{c:.0f}' for c in costs) + '};',
       '#ifndef NET_K', '#define NET_K 5', '#endif',
       'static void sn_setup(void) {',
       '    double Rb[9], T_[9];',
       '    for (int i = 0; i < 3; i++) for (int j = 0; j < 3; j++) { double a = 0; for (int q = 0; q < 3; q++) a += lc_Rs[3 * q + i] * lc_R5[3 * q + j]; Rb[3 * i + j] = a; }',
       '    m3tmul(R_bc, Rb, T_); m3mul(T_, R_bc, sn_Rc);',
       '    sn_fx320 = fx; sn_cx320 = cx; sn_cy320 = cy;',
       '    for (int i = 0; i < 3; i++) {',
       '        sn_vec[i] = (float)(lc_fm[0][i] / 9.81); sn_vec[3 + i] = (float)lc_gm[0][i];',
       '        sn_vec[6 + i] = (float)(lc_fm[1][i] / 9.81); sn_vec[9 + i] = (float)lc_gm[1][i];',
       '        double dv = lc_Rs[i] * (lc_V5[0] - lc_Vs[0]) + lc_Rs[3 + i] * (lc_V5[1] - lc_Vs[1]) + lc_Rs[6 + i] * (lc_V5[2] - lc_Vs[2]);',
       '        sn_vec[12 + i] = (float)(dv / (0.05 * 5 * 1 * 1 * 9.81));',
       '    }',
       '    double tr = (Rb[0] + Rb[4] + Rb[8] - 1) / 2;',
       '    tr = tr < -1 + 1e-6 ? -1 + 1e-6 : tr > 1 - 1e-6 ? 1 - 1e-6 : tr;',
       '    double th = acos(tr), w[3] = {Rb[7] - Rb[5], Rb[2] - Rb[6], Rb[3] - Rb[1]}, kk = th / (2 * sin(th) + 1e-6);',
       '    for (int i = 0; i < 3; i++) sn_vec[15 + i] = (float)(w[i] * kk);',
       '    sn_vec[18] = (float)(fx / 100.0);',
       '}',
       'void net_cam(double fx_, double cx_, double cy_, const double *Rbc) { fx = fx_; cx = cx_; cy = cy_; memcpy(R_bc, Rbc, sizeof R_bc); }',
       'void net_begin(const uint8_t *frame, const double *imu, int n) {',
       '    memset(lc_Rc, 0, sizeof lc_Rc); lc_Rc[0] = lc_Rc[4] = lc_Rc[8] = 1; memset(lc_Vi, 0, sizeof lc_Vi);',
       '    lc_have_row = 0; nt_frame = 0; nt_pos = 0; ns_have5 = 0;',
       '    lc_rows(imu, n, lc_fm[0], lc_gm[0]);',
       '    memcpy(lc_Rs, lc_Rc, sizeof lc_Rs); memcpy(lc_Vs, lc_Vi, sizeof lc_Vs);',
       '    sn_gray(frame, sn_g0);',
       '}',
       'int net_feed(const uint8_t *frame, const double *imu, int n) {',
       '    if (nt_frame >= NET_K) return 0;',
       '    nt_frame++;',
       '    double fm[3], gm[3];',
       '    lc_rows(imu, n, fm, gm);',
       '    if (nt_frame == NET_K) {',
       '        memcpy(lc_fm[1], fm, sizeof fm); memcpy(lc_gm[1], gm, sizeof gm);',
       '        memcpy(lc_R5, lc_Rc, sizeof lc_R5); memcpy(lc_V5, lc_Vi, sizeof lc_V5);',
       '        sn_gray(frame, sn_g5); ns_have5 = 1;',
       '        return 1;',
       '    }',
       '    return 0;',
       '}',
       'int net_nsteps(void) { return SN_STEPS; }',
       'double net_cost(int k) { return k < SN_STEPS ? sn_cost[k] : 0; }',
       'double net_total(void) { double s = 0; for (int k = 0; k < SN_STEPS; k++) s += sn_cost[k]; return s; }',
       'int net_pos(void) { return nt_pos; }',
       'int net_done(void) { return nt_pos >= SN_STEPS; }',
       'int net_tick(void) { if (nt_pos >= SN_STEPS || !ns_have5) return 0; if (nt_pos == 0) sn_setup(); sn_step(nt_pos); nt_pos++; return 1; }',
       'void net_out(double *mu, double *lv) { for (int i = 0; i < 3; i++) { mu[i] = sn_out[i]; lv[i] = sn_out[3 + i]; } }']
Path(a.out).write_text('\n'.join(o) + '\n'); print('wrote', a.out, 'steps', info['steps'])
