          f'            const v128_t xi = wasm_i32x4_min(wasm_i32x4_max(wasm_i32x4_sub(wasm_i32x4_trunc_sat_f32x4(wasm_f32x4_add(uk, one)), ione), im1), iW1);',
          f'            const v128_t yi = wasm_i32x4_min(wasm_i32x4_max(wasm_i32x4_sub(wasm_i32x4_trunc_sat_f32x4(wasm_f32x4_add(vk, one)), ione), im1), iH1);',
