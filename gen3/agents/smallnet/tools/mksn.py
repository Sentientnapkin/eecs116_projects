          f'            v128_t k0 = wasm_f32x4_add(wasm_f32x4_mul(R0, du), a0), k1 = wasm_f32x4_add(wasm_f32x4_mul(R1, du), a1), k2 = wasm_f32x4_add(wasm_f32x4_mul(R2, du), a2);',
          f'            v128_t iz = wasm_f32x4_div(fv, wasm_f32x4_max(k2, eps)), uk = wasm_f32x4_add(wasm_f32x4_mul(k0, iz), cxv), vk = wasm_f32x4_add(wasm_f32x4_mul(k1, iz), cyv);',
