"""mknet.py OUT_NET_C (--gslv SOLUTION_C | --run RUNDIR | --npz FILE) : generate the standalone, shape-agnostic net.c
(agents/cheap; interface documented in NOTES.md "Net interface").
  --gslv : weights block (LV_NET=1) of a GSLV build's solution.c (reference shape 16,24,32,48 / hidden 128 / res 64)
  --run  : netv2/lv4-style run dir (best.pt + result.json args chs/hidden; res 64)
  --npz  : arrays LC_W{i} (3,3,ci,co), LC_B{i} (co), LC_FW0 (19,32), LC_FB0 (32), LC_H1W (FH*FW*C_last+32, hid) rows in (h,w,c) then emb order,
           LC_H1B (hid), LC_H2W (hid,12), LC_H2B (12); scalars res (pooled input width; gray = 2*res x 1.5*res) optional (default 64)."""
import sys, re, json, argparse
from pathlib import Path
import numpy as np
HERE = Path(__file__).resolve().parent
ap = argparse.ArgumentParser(); ap.add_argument('out'); ap.add_argument('--gslv'); ap.add_argument('--run'); ap.add_argument('--npz'); ap.add_argument('--sigscale', type=float, default=1.0)
a = ap.parse_args()
def fmt(name, v):
    v = np.ascontiguousarray(v, dtype=np.float32).ravel()
    return [f'static const float {name}[{v.size}] = {{'] + [','.join(f'{x:.9g}' for x in v[i:i + 8]) + ',' for i in range(0, v.size, 8)] + ['};']
res = 64
if a.gslv:
    L = open(a.gslv).read().split('\n'); i0 = next(i for i in range(1500, len(L)) if L[i] == '#if LV_NET'); i1 = next(i for i in range(i0, len(L)) if L[i] == '#else')
    blk = L[i0 + 1:i1]; chs = [int(re.search(r'LC_C%d (\d+)' % k, '\n'.join(blk)).group(1)) for k in range(4)]
    m = re.search(r'#define LC_HID (\d+)', '\n'.join(blk)); hid = int(m.group(1)) if m else 128
    blk = [l for l in blk if not l.startswith('#define LC_')]
    assert a.sigscale == 1.0
    src = a.gslv
else:
    if a.run:
        import torch, math
        sys.path.insert(0, str(HERE.parent.parent / 'netv2/tools')); import lv4
        run = Path(a.run); args = json.load(open(run / 'result.json'))['args'] if (run / 'result.json').exists() else {}
        net = lv4.make_net(argparse.Namespace(chs=args.get('chs', '16,24,32,48'), deep=0, hidden=args.get('hidden', 128)))
        net.load_state_dict(torch.load(run / 'best.pt', map_location='cpu')); net.eval()
        A = {}; mods = list(net.cnn); k = 0
        for i in range(0, len(mods), 3):
            conv, bn = mods[i], mods[i + 1]; s = bn.weight / torch.sqrt(bn.running_var + bn.eps)
            A[f'LC_W{k}'] = (conv.weight * s[:, None, None, None]).permute(2, 3, 1, 0).detach().numpy(); A[f'LC_B{k}'] = (bn.bias - bn.running_mean * s).detach().numpy(); k += 1
        A['LC_FW0'] = net.fv[0].weight.detach().t().numpy(); A['LC_FB0'] = net.fv[0].bias.detach().numpy()
        C = A[f'LC_B{k-1}'].size; H = net.head[0].out_features; W1 = net.head[0].weight.detach()
        cnn = W1[:, :C * 12].reshape(H, C, 3, 4).permute(0, 2, 3, 1).reshape(H, 12 * C)
        A['LC_H1W'] = torch.cat([cnn, W1[:, C * 12:]], 1).t().numpy(); A['LC_H1B'] = net.head[0].bias.detach().numpy()
        A['LC_H2W'] = net.head[2].weight.detach().t().numpy(); A['LC_H2B'] = net.head[2].bias.detach().numpy()
        src = str(run)
    else:
        z = np.load(a.npz); A = {k: z[k] for k in z.files}; res = int(A.pop('res', 64)); src = a.npz
    A['LC_H2B'] = A['LC_H2B'].copy(); A['LC_H2B'][[3, 4, 5, 9, 10, 11]] += 2 * np.log(a.sigscale)
    nl = sum(1 for k in A if re.fullmatch(r'LC_W\d', k)); chs = [A[f'LC_B{k}'].size for k in range(nl)]; hid = A['LC_H1B'].size
    assert A['LC_H1W'].shape[0] == 12 * chs[-1] + 32, 'head input must be 3x4xC_last + 32'
    blk = []
    for k, v in A.items(): blk += fmt(k, v)
nl = len(chs); assert res % (1 << nl) == 0 and res // (1 << nl) == 4, 'final conv map must be 3x4'
hdr = [f'/* GENERATED by agents/cheap/tools/mknet.py from {src} -- learned velocity net, shape-agnostic sliced inference */',
       '#include <stdint.h>', '#include <string.h>', '#include <math.h>', '#include <wasm_simd128.h>', '#include "net.h"',
       '#define IMG_W 320', '#define IMG_H 240', f'#define LC_W {2 * res}', f'#define LC_H {3 * res // 2}', f'#define LC_PW {res}', f'#define LC_PH {3 * res // 4}',
       f'#define NET_NL {nl}', f'#define LC_HID {hid}'] + [f'#define LC_C{k} {c}' for k, c in enumerate(chs)] + [
       '#ifndef NET_K', '#define NET_K 5', '#endif',
       'static double fx, cx, cy, R_bc[9];',
       'static void m3mul(const double *a, const double *b, double *c) { for (int i = 0; i < 3; i++) for (int j = 0; j < 3; j++) c[3 * i + j] = a[3 * i] * b[j] + a[3 * i + 1] * b[3 + j] + a[3 * i + 2] * b[6 + j]; }',
       'static void m3tmul(const double *a, const double *b, double *c) { for (int i = 0; i < 3; i++) for (int j = 0; j < 3; j++) c[3 * i + j] = a[i] * b[j] + a[3 + i] * b[3 + j] + a[6 + i] * b[6 + j]; }']
body = (HERE / 'net_tmpl_body.c').read_text(); tail = (HERE / 'net_tmpl_tail.c').read_text()
Path(a.out).write_text('\n'.join(hdr + blk) + '\n' + body + '\n' + tail)
print('wrote', a.out, 'res', res, 'chs', chs, 'hid', hid)
