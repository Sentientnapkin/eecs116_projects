"""mkgslv.py RUN OUT.c [--sigscale s] [--base SRC]: GSLV-linejac source with the LV_NET=1 (v700b) weight block replaced by RUN's best.pt
(export_net.export, BN folded). Everything else byte-identical to the base source."""
import sys
from pathlib import Path
sys.path.insert(0, '/data/backups/rganapa/Sebastian/eecs116_projects/research/single_model/learned_c')
import export_net
BASE = Path('/data/backups/rganapa/Sebastian/eecs116_projects/research/single_model/linejac/final/gslv_linejac_arith.c')
run, out = Path(sys.argv[1]), Path(sys.argv[2])
ss = float(sys.argv[sys.argv.index('--sigscale') + 1]) if '--sigscale' in sys.argv else 1.0
base = Path(sys.argv[sys.argv.index('--base') + 1]) if '--base' in sys.argv else BASE
tmp = out.with_suffix('.w.h')
if ss != 1.0:  # LC_SIGSCALE is unused by the C: fold the sigma scale into the log-variance biases (both heads)
    import torch, math, shutil
    sd = torch.load(run / 'best.pt', map_location='cpu'); b = sd['head.2.bias'].clone(); b[3:6] += 2 * math.log(ss); b[9:12] += 2 * math.log(ss); sd['head.2.bias'] = b
    r2 = out.parent / (out.stem + '_run'); r2.mkdir(exist_ok=True); torch.save(sd, r2 / 'best.pt'); run = r2
export_net.export(str(run), str(tmp), 1.0, 64, 1.0)
s = base.read_text(); i = s.index('/* generated by export_net.py from runs/v700b')
j = s.index('static const float LC_H2B[12] = {', i); j = s.index('};', j) + 3
assert s[i:j].count('LC_H2B') == 1 and '#else' not in s[i:j]
s = s[:i] + tmp.read_text() + s[j:]
out.write_text(s); print('wrote', out)
