"""mkgslv2.py RUN OUT.c --base SRC [--sigscale s]: like mkgslv.py but for any lv4 shape (--chs, --hidden; no --deep):
writes the LV_NET=1 weight block (BN folded) incl. LC_C0..3 and LC_HID. Build with -DNS_GEN=1 for non-reference shapes."""
import sys, json, math, argparse
from pathlib import Path
import numpy as np, torch
sys.path.insert(0, str(Path(__file__).parent)); import lv4
run, out = Path(sys.argv[1]), Path(sys.argv[2])
ss = float(sys.argv[sys.argv.index('--sigscale') + 1]) if '--sigscale' in sys.argv else 1.0
base = Path(sys.argv[sys.argv.index('--base') + 1])
args = json.load(open(run / 'result.json'))['args'] if (run / 'result.json').exists() else {}
a = argparse.Namespace(chs=args.get('chs', '16,24,32,48'), deep=args.get('deep', 0), hidden=args.get('hidden', 128))
assert not a.deep
net = lv4.make_net(a); sd = torch.load(run / 'best.pt', map_location='cpu')
if ss != 1.0:
    b = sd['head.2.bias'].clone(); b[3:6] += 2 * math.log(ss); b[9:12] += 2 * math.log(ss); sd['head.2.bias'] = b
net.load_state_dict(sd); net.eval()
arrs = {}; mods = list(net.cnn); chs = []
for i in range(0, len(mods), 3):
    conv, bn = mods[i], mods[i + 1]
    s = bn.weight / torch.sqrt(bn.running_var + bn.eps)
    w = conv.weight * s[:, None, None, None]; bb = bn.bias - bn.running_mean * s
    arrs[f'LC_W{len(chs)}'] = w.permute(2, 3, 1, 0).detach().numpy(); arrs[f'LC_B{len(chs)}'] = bb.detach().numpy(); chs.append(conv.out_channels)
arrs['LC_FW0'] = net.fv[0].weight.detach().t().numpy(); arrs['LC_FB0'] = net.fv[0].bias.detach().numpy()
C = chs[-1]; H = net.head[0].out_features; W1 = net.head[0].weight.detach()
cnn = W1[:, :C * 12].reshape(H, C, 3, 4).permute(0, 2, 3, 1).reshape(H, 12 * C)
arrs['LC_H1W'] = torch.cat([cnn, W1[:, C * 12:]], 1).t().numpy(); arrs['LC_H1B'] = net.head[0].bias.detach().numpy()
arrs['LC_H2W'] = net.head[2].weight.detach().t().numpy(); arrs['LC_H2B'] = net.head[2].bias.detach().numpy()
lines = [f'/* generated by netv2 mkgslv2.py from {run}: BN folded, float32 */', '#define LC_SIGSCALE 1.0f',
         '#define LC_C0 %d\n#define LC_C1 %d\n#define LC_C2 %d\n#define LC_C3 %d' % tuple(chs)]
if H != 128: lines.append(f'#define LC_HID {H}')
for k, v in arrs.items():
    v = np.ascontiguousarray(v, dtype=np.float32).ravel()
    lines.append(f'static const float {k}[{v.size}] = {{')
    for i in range(0, v.size, 8): lines.append(','.join(f'{x:.9g}' for x in v[i:i + 8]) + ',')
    lines.append('};')
s = base.read_text(); i = s.index('/* generated by export_net.py from runs/v700b')
j = s.index('static const float LC_H2B[12] = {', i); j = s.index('};', j) + 3
s = s[:i] + '\n'.join(lines) + '\n' + s[j:]
out.write_text(s); print('wrote', out, 'chs', chs, 'hid', H)
